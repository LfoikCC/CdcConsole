CREATE SEQUENCE IF NOT EXISTS cdc_config_id START WITH 1 INCREMENT BY 1;
CREATE TABLE IF NOT EXISTS cdc_source (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  db_type VARCHAR(20) NOT NULL,
  host VARCHAR(255) NOT NULL,
  port INT NOT NULL,
  database_name VARCHAR(255) NOT NULL,
  username VARCHAR(255) NOT NULL,
  password VARCHAR(1000) NOT NULL,
  poll_interval_ms INT NOT NULL DEFAULT 500,
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
ALTER TABLE cdc_source ADD COLUMN IF NOT EXISTS poll_interval_ms INT NOT NULL DEFAULT 500;
CREATE TABLE IF NOT EXISTS cdc_target (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  target_type VARCHAR(30) NOT NULL,
  config_json CLOB NOT NULL,
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS table_mapping (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id BIGINT NOT NULL,
  target_id BIGINT NOT NULL,
  source_database VARCHAR(255),
  source_schema VARCHAR(255),
  source_table VARCHAR(255) NOT NULL,
  target_schema VARCHAR(255),
  target_table VARCHAR(255) NOT NULL,
  columns_json CLOB NOT NULL,
  include_operation BOOLEAN NOT NULL DEFAULT TRUE,
  include_captured_at BOOLEAN NOT NULL DEFAULT TRUE,
  operation_column VARCHAR(255) NOT NULL DEFAULT '_cdc_operation',
  captured_at_column VARCHAR(255) NOT NULL DEFAULT '_cdc_captured_at',
  captured_at_format VARCHAR(255) NOT NULL DEFAULT 'TIMESTAMP',
  operation_values_json CLOB NOT NULL DEFAULT '{}',
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT fk_mapping_source FOREIGN KEY (source_id) REFERENCES cdc_source(id),
  CONSTRAINT fk_mapping_target FOREIGN KEY (target_id) REFERENCES cdc_target(id)
);
ALTER TABLE table_mapping ADD COLUMN IF NOT EXISTS operation_column VARCHAR(255) NOT NULL DEFAULT '_cdc_operation';
ALTER TABLE table_mapping ADD COLUMN IF NOT EXISTS source_database VARCHAR(255);
UPDATE table_mapping SET source_database=(SELECT database_name FROM cdc_source WHERE cdc_source.id=table_mapping.source_id)
  WHERE (source_database IS NULL OR source_database='')
    AND EXISTS (SELECT 1 FROM cdc_source WHERE cdc_source.id=table_mapping.source_id AND database_name<>'');
UPDATE cdc_source SET database_name='' WHERE database_name<>'';
UPDATE table_mapping SET source_schema=NULL WHERE LOWER(source_schema)='dbo'
  AND source_id IN (SELECT id FROM cdc_source WHERE db_type<>'SQLSERVER');
UPDATE table_mapping SET target_schema=NULL WHERE LOWER(target_schema)='dbo'
  AND target_id IN (SELECT id FROM cdc_target WHERE target_type<>'SQLSERVER');
ALTER TABLE table_mapping ADD COLUMN IF NOT EXISTS captured_at_column VARCHAR(255) NOT NULL DEFAULT '_cdc_captured_at';
ALTER TABLE table_mapping ADD COLUMN IF NOT EXISTS captured_at_format VARCHAR(255) NOT NULL DEFAULT 'TIMESTAMP';
ALTER TABLE table_mapping ADD COLUMN IF NOT EXISTS operation_values_json CLOB NOT NULL DEFAULT '{}';
CREATE TABLE IF NOT EXISTS cdc_checkpoint (
  mapping_id BIGINT PRIMARY KEY,
  last_lsn VARCHAR(100) NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_checkpoint_mapping FOREIGN KEY (mapping_id) REFERENCES table_mapping(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS cdc_snapshot (
  mapping_id BIGINT NOT NULL,
  row_key VARCHAR(2000) NOT NULL,
  row_json CLOB NOT NULL,
  PRIMARY KEY (mapping_id, row_key),
  CONSTRAINT fk_snapshot_mapping FOREIGN KEY (mapping_id) REFERENCES table_mapping(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS app_setting (
  setting_key VARCHAR(100) PRIMARY KEY,
  setting_value VARCHAR(1000) NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
