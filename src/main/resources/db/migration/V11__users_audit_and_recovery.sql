 mapping_version BIGINT NOT NULL, generation BIGINT NOT NULL, mode VARCHAR(30) NOT NULL, start_sequence BIGINT NOT NULL,
 boundary_sequence BIGINT NOT NULL, requested_at TIMESTAMP WITH TIME ZONE,
 actor_id BIGINT NOT NULL, expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);
