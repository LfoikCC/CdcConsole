CREATE TABLE console_user (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(80) NOT NULL UNIQUE, name VARCHAR(120) NOT NULL,
 email VARCHAR(255), role VARCHAR(20) NOT NULL, password_hash VARCHAR(100) NOT NULL,
 enabled BOOLEAN NOT NULL DEFAULT TRUE, deleted BOOLEAN NOT NULL DEFAULT FALSE,
 last_login_at TIMESTAMP WITH TIME ZONE, created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE console_session (
 id VARCHAR(64) PRIMARY KEY, user_id BIGINT, csrf VARCHAR(64) NOT NULL,
 expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_console_session_user ON console_session(user_id);
CREATE TABLE console_bootstrap (id INT PRIMARY KEY);
CREATE TABLE console_audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 occurred_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
 actor_id BIGINT, actor VARCHAR(120) NOT NULL, action VARCHAR(40) NOT NULL,
 resource_type VARCHAR(40) NOT NULL, resource_id VARCHAR(160), resource_name VARCHAR(255),
 result VARCHAR(20) NOT NULL, ip VARCHAR(100), request_id VARCHAR(64), reason VARCHAR(2000),
 before_json CLOB, after_json CLOB, recovery_id VARCHAR(64)
);
CREATE INDEX idx_console_audit_time ON console_audit(occurred_at,id);
CREATE TABLE checkpoint_history (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, task_id BIGINT NOT NULL,
 subscription_table_id BIGINT NOT NULL, sampled_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
 capture_position CLOB, delivery_position CLOB, capture_lag_ms BIGINT,
 pending_events BIGINT NOT NULL, pending_bytes BIGINT NOT NULL, delivery_wait_ms BIGINT
);
CREATE INDEX idx_checkpoint_history_task ON checkpoint_history(task_id,sampled_at);
