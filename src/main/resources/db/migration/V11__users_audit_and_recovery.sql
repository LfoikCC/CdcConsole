CREATE TABLE recovery_job (
 id VARCHAR(64) PRIMARY KEY, task_id BIGINT NOT NULL, subscription_table_id BIGINT NOT NULL,
 mapping_id BIGINT NOT NULL, mapping_version BIGINT NOT NULL, generation BIGINT NOT NULL,
 mode VARCHAR(30) NOT NULL, status VARCHAR(30) NOT NULL,
 start_sequence BIGINT NOT NULL, cursor_sequence BIGINT NOT NULL, boundary_sequence BIGINT NOT NULL,
 requested_at TIMESTAMP WITH TIME ZONE, created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP, last_error VARCHAR(2000),
 processed_events BIGINT DEFAULT 0 NOT NULL, snapshot_complete BOOLEAN DEFAULT FALSE NOT NULL,
 actor_id BIGINT, actor VARCHAR(120), completed_at TIMESTAMP WITH TIME ZONE
);
