 job_id VARCHAR(64) NOT NULL, part_no BIGINT NOT NULL, segment_path VARCHAR(2000) NOT NULL,
 checksum VARCHAR(128) NOT NULL, event_count INT NOT NULL, payload_bytes BIGINT NOT NULL,
 PRIMARY KEY(job_id,part_no)
);
