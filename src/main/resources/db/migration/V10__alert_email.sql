CREATE TABLE mail_rule (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, config_json CLOB NOT NULL,
 alert_cursor BIGINT NOT NULL DEFAULT 0, created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE mail_delivery (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, rule_id BIGINT, alert_id BIGINT,
 recipient VARCHAR(255) NOT NULL, subject VARCHAR(500) NOT NULL, body CLOB NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING', attempts INT NOT NULL DEFAULT 0,
 due_at TIMESTAMP WITH TIME ZONE NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 sent_at TIMESTAMP WITH TIME ZONE, last_error VARCHAR(2000),
 CONSTRAINT mail_delivery_unique UNIQUE(rule_id,alert_id,recipient)
);
CREATE INDEX mail_delivery_due ON mail_delivery(status,due_at);
CREATE TABLE mail_rule_seen (
 rule_id BIGINT NOT NULL, alert_id BIGINT NOT NULL, PRIMARY KEY(rule_id,alert_id),
 CONSTRAINT mail_seen_rule FOREIGN KEY(rule_id) REFERENCES mail_rule(id) ON DELETE CASCADE,
 CONSTRAINT mail_seen_alert FOREIGN KEY(alert_id) REFERENCES alert_event(id) ON DELETE CASCADE
);
