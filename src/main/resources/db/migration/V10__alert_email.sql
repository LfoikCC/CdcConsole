CREATE TABLE mail_config (
 id INT PRIMARY KEY, enabled BOOLEAN NOT NULL DEFAULT FALSE, host VARCHAR(255) NOT NULL DEFAULT '',
 port INT NOT NULL DEFAULT 587, secure VARCHAR(20) NOT NULL DEFAULT 'starttls', username VARCHAR(255) NOT NULL DEFAULT '',
 password VARCHAR(1000) NOT NULL DEFAULT '', from_name VARCHAR(255) NOT NULL DEFAULT 'CDC 监控', from_email VARCHAR(255) NOT NULL DEFAULT ''
);
