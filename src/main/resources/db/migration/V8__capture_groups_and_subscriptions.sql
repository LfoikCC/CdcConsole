CREATE TABLE IF NOT EXISTS cdc_capture_group (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id BIGINT NOT NULL,
  source_database VARCHAR(255),
  source_schema VARCHAR(255),
  source_table VARCHAR(255) NOT NULL,
  sync_mode VARCHAR(40) NOT NULL DEFAULT 'FULL_INCREMENTAL',
  canonical_schema_json CLOB NOT NULL DEFAULT '{}',
  status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
  capture_position_json CLOB,
  generation BIGINT NOT NULL DEFAULT 0,
  max_pending_bytes BIGINT NOT NULL DEFAULT 10737418240,
  last_error VARCHAR(4000),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_capture_group_source FOREIGN KEY (source_id) REFERENCES cdc_source(id) ON DELETE CASCADE
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_capture_group_source_table
  ON cdc_capture_group(source_id, source_database, source_schema, source_table);

CREATE TABLE IF NOT EXISTS cdc_target_subscription (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  capture_group_id BIGINT NOT NULL,
  mapping_id BIGINT,
  target_id BIGINT NOT NULL,
  target_schema VARCHAR(255),
  target_table VARCHAR(255) NOT NULL,
  mapping_override_json CLOB NOT NULL DEFAULT '{}',
  mapping_version BIGINT NOT NULL DEFAULT 1,
  status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
  delivery_position_json CLOB,
  max_pending_bytes BIGINT NOT NULL DEFAULT 10737418240,
  pending_bytes BIGINT NOT NULL DEFAULT 0,
  pending_events BIGINT NOT NULL DEFAULT 0,
  last_error VARCHAR(4000),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_subscription_group FOREIGN KEY (capture_group_id) REFERENCES cdc_capture_group(id) ON DELETE CASCADE,
  CONSTRAINT fk_subscription_target FOREIGN KEY (target_id) REFERENCES cdc_target(id) ON DELETE CASCADE,
  CONSTRAINT fk_subscription_mapping FOREIGN KEY (mapping_id) REFERENCES table_mapping(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_subscription_group ON cdc_target_subscription(capture_group_id, status, id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_subscription_mapping ON cdc_target_subscription(mapping_id);

CREATE TABLE IF NOT EXISTS cdc_capture_batch (
  capture_batch_id VARCHAR(128) PRIMARY KEY,
  capture_group_id BIGINT NOT NULL,
  generation BIGINT NOT NULL,
  source_start_position CLOB,
  source_end_position CLOB,
  segment_path VARCHAR(2000) NOT NULL,
  checksum VARCHAR(64) NOT NULL,
  event_count INT NOT NULL,
  payload_bytes BIGINT NOT NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'STAGED',
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_capture_batch_group FOREIGN KEY (capture_group_id) REFERENCES cdc_capture_group(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_capture_batch_group ON cdc_capture_batch(capture_group_id, generation, created_at, capture_batch_id);

CREATE TABLE IF NOT EXISTS cdc_subscription_batch (
  subscription_batch_id VARCHAR(160) PRIMARY KEY,
  subscription_id BIGINT NOT NULL,
  capture_batch_id VARCHAR(128) NOT NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'STAGED',
  attempt_count INT NOT NULL DEFAULT 0,
  next_retry_at TIMESTAMP WITH TIME ZONE,
  last_error VARCHAR(4000),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  delivered_at TIMESTAMP WITH TIME ZONE,
  CONSTRAINT fk_subscription_batch_subscription FOREIGN KEY (subscription_id) REFERENCES cdc_target_subscription(id) ON DELETE CASCADE,
  CONSTRAINT fk_subscription_batch_capture FOREIGN KEY (capture_batch_id) REFERENCES cdc_capture_batch(capture_batch_id) ON DELETE CASCADE
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_subscription_capture_batch ON cdc_subscription_batch(subscription_id, capture_batch_id);
CREATE INDEX IF NOT EXISTS idx_subscription_batch_head ON cdc_subscription_batch(subscription_id, status, created_at, subscription_batch_id);

ALTER TABLE cdc_delivery_part ADD COLUMN IF NOT EXISTS subscription_batch_id VARCHAR(160);
CREATE INDEX IF NOT EXISTS idx_delivery_part_subscription ON cdc_delivery_part(subscription_batch_id);
